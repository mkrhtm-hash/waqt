const FALLBACK_LOOK = { shape: 'round', metal: 'steel', dial: '#15161a', bezel: 'smooth', dialStyle: 'sunburst', strap: 'bracelet', hands: 'white' }
const METAL_BY_MATERIAL = { Steel: 'steel', Gold: 'yellow', 'Rose Gold': 'rose', Platinum: 'platinum', 'Two-Tone': 'twotone' }

/** Illustration spec for a watch from the API (falls back to a generic look for new references). */
export function getLook(watch) {
  if (!watch) return FALLBACK_LOOK
  return looksByRef[watch.ref] || { ...FALLBACK_LOOK, metal: METAL_BY_MATERIAL[watch.material] || 'steel' }
}

export const getBrandStyle = (slug) => brandStyle[slug] || { tagline: { en: '', ar: '' }, accent: '#7a5a2b', origin: null }
